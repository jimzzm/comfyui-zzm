"""
图像分辨率 — 由「宽高比 + 百万像素 + 倍数」算出宽高，或直接用自定义宽高，并给出对应空 Latent。

固定比例走 ComfyUI 官方 ResolutionSelector 的算法（comfy_extras/nodes_resolution.py）：
    scale = sqrt(百万像素 × 1024² / (宽比 × 高比))
    宽度  = round(宽比 × scale / 倍数) × 倍数
    高度  = round(高比 × scale / 倍数) × 倍数
选「自定义」时忽略百万像素与倍数，直接用「宽度」「高度」两个值。

比例表用的都是通用画幅（1:1 / 2:3 / 16:9 这类），没有引入外部实现。
倍数只给 8 / 16 / 32 / 64：本节点要顺手产出 Latent，宽高必须能被 8 整除，
否则 latent 与像素尺寸对不齐（官方节点不建 latent，所以它敢用 4 作步长）。

⚠️ 参数顺序尽量保持原样：前四项是 宽度 / 高度 / 宽高比 / 批量大小。
ComfyUI 载入工作流时按顺序把 widgets_values 填回各控件，顺序一变老工作流的存档值就会错位。
（「反转尺寸」已于 2026-11-10 删除——比例本身正反都齐，不需要它。）

⚠️ LEGACY_SIZES 是旧版固定尺寸预设，只为了让老工作流精确恢复（1080×608 这种非标准尺寸也算得准）。
   等新节点实测没问题后，整块连同 INPUT_TYPES 里的拼接、run() 里的分支一起删掉即可。

前端 web/js/resolution_preview.js 会把最终分辨率实时写到输出插槽左侧，
它内置了一份同样的比例表 —— 改这里的数据时记得同步那一份。
"""

import math

import torch

CUSTOM = "自定义"

# ---------------------------------------------------------------------------
# 比例表（宽比, 高比）
# ---------------------------------------------------------------------------
ASPECT_RATIOS = {
    "1:1（方形）": (1, 1),
    "2:3（竖版照片）": (2, 3),
    "3:2（横版照片）": (3, 2),
    "3:4（竖版标准）": (3, 4),
    "4:3（标准）": (4, 3),
    "5:7（竖版）": (5, 7),
    "9:16（竖屏）": (9, 16),
    "16:9（宽屏）": (16, 9),
    "21:9（超宽）": (21, 9),
    "1:2（长竖）": (1, 2),
    "2:1（长横）": (2, 1),
}

# ---------------------------------------------------------------------------
# 【待删除】旧版固定尺寸预设 —— 仅为兼容老工作流保留
# 新节点实测通过后，删掉本字典 + INPUT_TYPES 里的拼接 + run() 里的 LEGACY 分支
# ---------------------------------------------------------------------------
LEGACY_SIZES = {
    "512×512（1:1）": (512, 512),
    "1024×1024（1:1）": (1024, 1024),
    "2048×2048（1:1）": (2048, 2048),
    "1080×608（135:76）": (1080, 608),
    "1024×768（4:3）": (1024, 768),
    "1280×720（16:9）": (1280, 720),
    "800×1280（5:8）": (800, 1280),
    "1536×1024（3:2）": (1536, 1024),
    "1920×1080（16:9）": (1920, 1080),
    "1200×1920（5:8）": (1200, 1920),
    "2560×1440（16:9）": (2560, 1440),
    "3840×2160（16:9）": (3840, 2160),
}


class AspectRatio:
    """算宽高 + 直接产出对应的空 Latent。"""

    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                # 前四项顺序不可动：老工作流按位置恢复这些值
                "宽度": ("INT", {"default": 1024, "min": 64, "max": 8192, "step": 8}),
                "高度": ("INT", {"default": 1536, "min": 64, "max": 8192, "step": 8}),
                "宽高比": (
                    list(ASPECT_RATIOS.keys()) + list(LEGACY_SIZES.keys()) + [CUSTOM],
                    {"default": "1:1（方形）"},
                ),
                "批量大小": ("INT", {"default": 1, "min": 1, "max": 64}),
                # 以下两项是新增的，追加在末尾
                "百万像素": (
                    "FLOAT",
                    {"default": 1.0, "min": 0.1, "max": 16.0, "step": 0.1},
                ),
                "倍数": (
                    ["8", "16", "32", "64"],
                    {"default": "8"},
                ),
            },
        }

    RETURN_TYPES = ("INT", "INT", "INT", "LATENT")
    RETURN_NAMES = ("宽度", "高度", "批量大小", "Latent图像")
    FUNCTION = "run"
    CATEGORY = "⚡ zzm工具箱"
    SEARCH_ALIASES = [
        "zzm", "resolution", "分辨率", "图像分辨率",
        "宽高比", "图像高宽比", "aspect ratio", "megapixel", "latent", "自定义尺寸",
    ]
    DESCRIPTION = (
        "两种用法：\n"
        "· 选固定宽高比（1:1、16:9 这类）→ 由「百万像素」算出像素尺寸，每条边取到「倍数」的整数倍，宽高栏被忽略。\n"
        "· 选「自定义」→ 直接用「宽度」「高度」，百万像素与倍数不参与。\n"
        "带「×」的旧预设（如 1024×1024（1:1））只为兼容老工作流保留，新建工作流请用上面的比例。\n"
        "同时输出同尺寸的空 Latent，可直接接 KSampler。\n"
        "算法与官方分辨率选择器一致：1.0 百万像素 ≈ 1024×1024（方形）。"
    )

    def run(self, 宽度, 高度, 宽高比, 批量大小, 百万像素, 倍数):
        if 宽高比 == CUSTOM:
            width = int(宽度)
            height = int(高度)
        elif 宽高比 in LEGACY_SIZES:  # 【待删除】旧预设分支
            width, height = LEGACY_SIZES[宽高比]
        else:
            w_ratio, h_ratio = ASPECT_RATIOS[宽高比]
            multiple = int(倍数)
            total_pixels = float(百万像素) * 1024 * 1024
            scale = math.sqrt(total_pixels / (w_ratio * h_ratio))
            width = int(round(w_ratio * scale / multiple) * multiple)
            height = int(round(h_ratio * scale / multiple) * multiple)

        latent = torch.zeros([批量大小, 4, height // 8, width // 8])

        return (width, height, 批量大小, {"samples": latent})
